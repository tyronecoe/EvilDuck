#!/usr/bin/env python3
"""Read-only evidence/scope checks; no compilation, network or device access."""
import argparse
import hashlib
import json
import pathlib
import stat
import subprocess
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
BASE = 'b6d85e6da700774345c584f4f67fa5df4f0ea854'
APP_SHA = '53acc374ef38be652b6847d4b84f2dc7d42fa73a3dd54ea62d5208be4cbc0167'
ZIP_SHA = '9a60e91e142fea74b746bef352d16139cccaf9fd45ca5e5a10549c91b846dc9e'
ALLOWED = {
    'docs/routeb-accepted-baseline.md', 'docs/routeb-accepted-baseline.json',
    'docs/routeb-accepted-compatibility.md', 'docs/routeb-next-compatibility-release.md',
    'docs/routeb-acceptance-closeout-report.md', 'docs/routeb-acceptance-closeout-checks.json',
    'docs/routeb-acceptance-closeout-publication.json', 'tests/acceptance_closeout/verify.py'
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def require(value, label):
    if not value:
        raise ValueError(label)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build-root', type=pathlib.Path, required=True,
                        help='Existing text/keyboard build; never generated by this check')
    args = parser.parse_args()
    subprocess.run(['git', 'merge-base', '--is-ancestor', BASE, 'HEAD'], cwd=ROOT, check=True)
    changed = set(subprocess.check_output(['git', 'diff', '--name-only', BASE], cwd=ROOT, text=True).splitlines())
    changed.update(subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], cwd=ROOT, text=True).splitlines())
    require(changed <= ALLOWED, 'changes outside documentation/audit scope')
    rows = []
    for entry in subprocess.check_output(['git', 'ls-tree', '-rz', BASE], cwd=ROOT).split(b'\0'):
        if not entry:
            continue
        metadata, name = entry.split(b'\t', 1)
        mode, kind, oid = metadata.decode().split()
        path = ROOT / name.decode()
        require(kind == 'blob' and mode in ('100644', '100755'), 'unsupported baseline entry')
        require(path.is_file() and not path.is_symlink(), 'missing/nonregular baseline file')
        data = path.read_bytes()
        actual = subprocess.check_output(['git', 'hash-object', '--stdin'], input=data, cwd=ROOT).decode().strip()
        require(actual == oid, 'baseline bytes changed: ' + name.decode())
        require(bool(path.stat().st_mode & stat.S_IXUSR) == (mode == '100755'), 'baseline mode changed')
        rows.append([name.decode(), mode, sha(data)])
    receipt = json.loads((ROOT / 'docs/text-keyboard-build.json').read_text())
    require(receipt['status'] == 'PASS' and receipt['text_keyboard_verified'] is True, 'missing historical build proof')
    for row in receipt['source_inventory']:
        path = args.build_root / 'candidate' / row['file']
        require(path.is_file() and not path.is_symlink(), 'missing composed source')
        data = path.read_bytes()
        require(len(data) == row['size'] and sha(data) == row['sha256'], 'composed source mismatch')
    for row in receipt['artifacts']:
        path = args.build_root / 'build' / row['file']
        require(path.is_file() and not path.is_symlink(), 'missing historical artifact')
        data = path.read_bytes()
        require(len(data) == row['size'] and sha(data) == row['sha256'], 'historical artifact mismatch')
    accepted = json.loads((ROOT / 'docs/routeb-accepted-baseline.json').read_text())
    require(accepted['release_commit'] == BASE and accepted['application_bytes'] == 1412400,
            'accepted baseline mismatch')
    require(accepted['application_sha256'] == accepted['future_rollback_application_sha256'] == APP_SHA,
            'wrong future rollback policy')
    archive = ROOT / 'downloads/evilduck-routeb-text-keyboard-macos-v1.zip'
    raw = archive.read_bytes()
    require(len(raw) == 2336378 and sha(raw) == ZIP_SHA, 'historical ZIP changed')
    with zipfile.ZipFile(archive) as z:
        require(z.testzip() is None and len(z.namelist()) == 24, 'ZIP integrity/inventory')
        app = z.read('application.bin')
        require(len(app) == 1412400 and sha(app) == APP_SHA, 'accepted app changed')
        manifest = json.loads(z.read('manifest.json'))
        for name, row in manifest['support_files'].items():
            data = z.read(name)
            require(len(data) == row['bytes'] and sha(data) == row['sha256'], 'ZIP support binding')
    freeze = subprocess.run([sys.executable, str(ROOT / 'tests/stage28h/verify_freeze.py')],
                            cwd=ROOT, text=True, capture_output=True, check=True)
    require('235 protected Stage26 files byte-identical' in freeze.stdout, 'freeze result missing')
    historical = {}
    for suffix in ('test-results', 'package-tests', 'installer-tests'):
        record = json.loads((ROOT / ('docs/text-keyboard-' + suffix + '.json')).read_text())
        historical[suffix] = dict(counts=record['counts'], executed_this_closeout=False)
    print(json.dumps(dict(status='PASS', baseline=BASE, baseline_files_and_modes=len(rows),
        baseline_inventory_sha256=sha(json.dumps(rows, separators=(',', ':')).encode()),
        composed_sources_rehashed=len(receipt['source_inventory']),
        existing_build_artifacts_rehashed=len(receipt['artifacts']),
        public_archive_bytes=len(raw), public_archive_sha256=sha(raw),
        accepted_application_bytes=len(app), accepted_application_sha256=sha(app),
        support_bindings_rehashed=len(manifest['support_files']), zip_crc='PASS',
        stage26_freeze=freeze.stdout.strip(), historical_receipts=historical,
        checks='integrity and documentation scope; no new firmware behavior tested',
        allowed_changes_only=True, observed_new_paths=sorted(changed),
        python=sys.version.split()[0], firmware_built=False, firmware_modified=False,
        physical_testing=False, hardware_access=False), indent=2))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError, zipfile.BadZipFile, subprocess.CalledProcessError) as error:
        print(json.dumps(dict(status='FAIL', reason=str(error))), file=sys.stderr)
        raise SystemExit(1)
